#!/usr/bin/env node
'use strict';

// Regenerate functions/blog/live-files.txt from production.
//
// The restore walk can only find what it can reach, and a page nothing links to
// is invisible to it. This records what production actually served so the next
// deploy can fetch each path by name. Run it after adding a landing page, then
// commit the result.

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const { reconcileProduction, isBlogOwned, MANIFEST } = require('./sync-live');
const { PUBLIC_DIR, BLOG_DIR } = require('./build');

const HEADER = '# Live paths on gitsyn.cc that a blog-only deploy directory must restore.\n'
  + '# Generated by `npm run blog:manifest`. One path per line; # comments are ignored.\n';

async function main() {
  // Seed the crawl from the blog's own rendered pages, because the walk skips
  // /blog and a site asset referenced only from an article would otherwise go
  // unrecorded.
  const stage = fs.mkdtempSync(path.join(os.tmpdir(), 'blog-manifest-'));
  try {
    fs.cpSync(BLOG_DIR, path.join(stage, 'blog'), { recursive: true });
    fs.copyFileSync(path.join(PUBLIC_DIR, 'blog.css'), path.join(stage, 'blog.css'));

    const { restored, drift, unreachable } = await reconcileProduction({ publicDir: stage });
    if (unreachable.length) {
      throw new Error(`cannot read ${unreachable.length} live file(s): ${unreachable.map((f) => `${f.path} (${f.reason})`).join(', ')}`);
    }
    if (drift.length) {
      console.error(`note: ${drift.length} file(s) differ from the local copy; the manifest records production's version`);
    }

    const target = path.join(__dirname, MANIFEST);
    const known = fs.existsSync(target)
      ? fs.readFileSync(target, 'utf8').split(/\r?\n/).filter((line) => line.trim() && !line.startsWith('#'))
      : [];
    // app-mockups.png and feature-collab.png are live but nothing on the site
    // links to them, so no crawl can discover them. Whatever the current tree
    // holds is recorded too, which is how a blog-only checkout learns to fetch
    // them by name.
    const local = fs.readdirSync(PUBLIC_DIR, { recursive: true })
      .map((p) => String(p).split(path.sep).join('/'))
      .filter((rel) => fs.statSync(path.join(PUBLIC_DIR, rel)).isFile())
      .filter((rel) => !isBlogOwned(rel));
    const paths = [...new Set([...known, ...local, ...restored.map((f) => f.path)])].sort();

    fs.writeFileSync(target, `${HEADER}${paths.join('\n')}\n`, 'utf8');
    console.log(JSON.stringify({ manifest: target, paths: paths.length, added: paths.length - known.length }));
  } finally {
    fs.rmSync(stage, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(String((error && error.message) || error));
  process.exit(1);
});
